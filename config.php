<?php
/**
 * Media Library 設定ファイル
 *
 * このファイルは .htaccess で直接アクセスを禁止しています。
 */

return [
    // 扱うメディアの種類。拡張子と呼び名を、ここ1か所にまとめている。
    // どの拡張子を写真として扱い、どれを動画として扱うかは、フォルダの分け方とは
    // 別のことなので、下の roots ではなくこちらで決める。
    //
    //   label      … 画面に出す呼び名（「写真 12 枚」の「写真」にあたる部分）
    //   unit       … 件数の数え方の単位（「写真 12 枚」の「枚」にあたる部分）
    //   extensions … その種類として扱う拡張子（小文字で記載）
    //
    // キーの 'image' と 'video' は、プログラムから名指しで使っている。
    // 動画は一覧・拡大表示で再生できる形にし、フォルダ情報のサムネイルには
    // 画像を使う、という判断をこの2つの名前で行っているため、変更しないこと。
    'kinds' => [
        'image' => [
            'label'      => '写真',
            'unit'       => '枚',
            'extensions' => ['jpg', 'jpeg', 'png', 'gif', 'webp', 'avif', 'bmp'],
        ],
        'video' => [
            'label'      => '動画',
            'unit'       => '本',
            // ブラウザがそのまま再生できる形式に絞っている。
            // mov（QuickTime）は中身が H.264 なら多くのブラウザで再生できるが、
            // 撮影機材によっては再生できないことがある。
            'extensions' => ['mp4', 'm4v', 'mov', 'webm', 'ogv'],
        ],
    ],

    // 写真・動画を置くフォルダ（ルート）の一覧。通常は1つでよい。
    // 別の場所にもう1つツリーを持ちたいときだけ足す。そのときは画面上部のタブが、
    // 種類の絞り込みに加えてルートの切り替えも兼ねるようになる。
    // キーはURLの root= に入る値なので、英数字の短い名前にしておく。
    //
    //   label … パス表示（パンくず）の先頭に出す名前
    //   dir   … 実際のフォルダ。このファイルからの相対パス、または絶対パス
    //   url   … ブラウザから参照するときのURL（index.php から見た相対パス）
    //           dir を公開ディレクトリ外に変更した場合、この方式では表示できない
    //   kinds … そのフォルダで表示するメディアの種類（上の kinds のキー）。
    //           複数書くと、写真と動画が同じ一覧に並ぶ。省略するとすべて。
    'roots' => [
        'media' => [
            'label' => 'メディア',
            'dir'   => __DIR__ . '/media',
            'url'   => 'media',
            'kinds' => ['image', 'video'],   // 写真と動画を同じ一覧に並べる
        ],
    ],

    // 最初に開くルート（roots のキー）
    'default_root' => 'media',

    // 画面上部に表示するタイトル
    'title' => 'Media Library',

    // 1ページあたりの表示件数。0 を指定すると全件を1ページに表示する。
    'per_page' => 60,

    // サムネイルの表示サイズ（px）。CSSのグリッド幅として使う。
    'thumb_size' => 200,

    // 一覧の見せ方の初期値： 'grid'（サムネイルを並べる）| 'list'（1行ずつ並べる）
    // 画面右上のボタン、または一覧の下の「設定」から切り替えられる。
    // 変えた内容はそのブラウザに覚えさせるので、他の人の画面には影響しない。
    'default_view' => 'grid',

    // 並び順の初期値： 'name' | 'date' | 'size'
    'default_sort' => 'name',

    // 並び方向の初期値： 'asc' | 'desc'
    'default_order' => 'asc',

    // 写真・動画・フォルダの編集（名前の変更・移動・削除）を禁止する。
    // true にすると画面から操作ボタンが消え、サーバー側でも処理を受け付けない。
    // 閲覧だけしてほしい相手に見せるときに使う。
    'read_only' => false,

    // 動画を再生し始めるときに音を消しておく。
    // 開いた直後は無音で再生され、プレーヤーの音量ボタンで音を出せる。
    // 不意に音が出ると困る場面のほうが多いので、既定では音を消している。
    //
    // ここで書くのは「はじめて開いたときの値」で、一覧の下の「設定」から
    // 変更できる。変えた内容はそのブラウザに覚えさせるので、
    // 同じページを見ている他の人には影響しない。
    'video_muted' => true,

    // 動画を再生するときの表示の大きさ。こちらも「設定」から変更できる。
    //
    //   'original' … 動画そのものの大きさで表示する。
    //                画面に収まらないときだけ、収まる大きさまで縮める。
    //   'fit'      … 画面の幅いっぱいまで広げる。
    'video_size' => 'original',

    // 削除したファイル・フォルダの退避先。各ルートのフォルダからの相対パスで指定する。
    // 先頭がドットの名前にしておくと、一覧には表示されない。
    'trash_dir' => '.trash',

    // 新しい名前として受け付ける最大文字数
    'max_name_length' => 100,

    // ---- アップロード ----------------------------------------------
    // 一覧の上にファイル（フォルダ）を落とすと、開いているフォルダに取り込む。
    // 受け付ける拡張子は、開いているルートで表示している種類（kinds）のもの。
    // read_only が true のときは、この機能ごと無効になる。

    // ファイル1つあたりの上限（バイト）。0 を指定すると上限なし。
    'max_upload_size' => 2 * 1024 * 1024 * 1024, // 2GB

    // 送るときに切り分ける大きさ（バイト）。
    // 大きな動画でもサーバーの upload_max_filesize / post_max_size に
    // 引っかからないよう、この大きさずつ送って、向こうで継ぎ足している。
    // サーバーの上限のほうが小さいときは、そちらに合わせて自動で小さくする。
    'upload_chunk_size' => 4 * 1024 * 1024, // 4MB

    // 組み立て途中のファイルの置き場所。各ルートのフォルダからの相対パスで指定する。
    // 先頭がドットの名前にしておくと、一覧には表示されない。
    'upload_temp_dir' => '.upload',
];
