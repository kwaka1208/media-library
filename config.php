<?php
/**
 * Media Library 設定ファイル
 *
 * このファイルは .htaccess で直接アクセスを禁止しています。
 */

return [
    // 表示するフォルダ（ルート）の一覧。画面上部のタブで切り替える。
    // キーはURLの root= に入る値なので、英数字の短い名前にしておく。
    //
    //   label      … タブに表示する名前
    //   dir        … 実際のフォルダ。このファイルからの相対パス、または絶対パス
    //   url        … ブラウザから参照するときのURL（index.php から見た相対パス）
    //                 dir を公開ディレクトリ外に変更した場合、この方式では表示できない
    //   extensions … 表示対象とする拡張子（小文字で記載）
    //   unit       … 件数の数え方の単位（「写真 12 枚」の「枚」にあたる部分）
    //   kind       … 'image' か 'video'。動画は一覧・拡大表示で再生できる形にする
    'roots' => [
        'photos' => [
            'label'      => '写真',
            'dir'        => __DIR__ . '/photos',
            'url'        => 'photos',
            'extensions' => ['jpg', 'jpeg', 'png', 'gif', 'webp', 'avif', 'bmp'],
            'unit'       => '枚',
            'kind'       => 'image',
        ],
        'movies' => [
            'label'      => '動画',
            'dir'        => __DIR__ . '/movies',
            'url'        => 'movies',
            // ブラウザがそのまま再生できる形式に絞っている。
            // mov（QuickTime）は中身が H.264 なら多くのブラウザで再生できるが、
            // 撮影機材によっては再生できないことがある。
            'extensions' => ['mp4', 'm4v', 'mov', 'webm', 'ogv'],
            'unit'       => '本',
            'kind'       => 'video',
        ],
    ],

    // 最初に開くルート（roots のキー）
    'default_root' => 'photos',

    // 画面上部に表示するタイトル
    'title' => 'Media Library',

    // 1ページあたりの表示件数。0 を指定すると全件を1ページに表示する。
    'per_page' => 60,

    // サムネイルの表示サイズ（px）。CSSのグリッド幅として使う。
    'thumb_size' => 200,

    // 一覧の見せ方の初期値： 'grid'（サムネイルを並べる）| 'list'（1行ずつ並べる）
    // 画面右上のボタン、または「設定」から切り替えられる。
    // 変えた内容はそのブラウザに覚えさせるので、他の人の画面には影響しない。
    'default_view' => 'grid',

    // 並び順の初期値： 'name' | 'date' | 'size'
    'default_sort' => 'name',

    // 並び方向の初期値： 'asc' | 'desc'
    'default_order' => 'asc',

    // 写真・動画・フォルダの編集（名前の変更・移動・削除）を禁止する。
    // true にすると画面から操作ボタンが消え、サーバー側でも処理を受け付けない。
    // 閲覧だけしてほしい相手に見せるときに使う。
    'read_only' => false,

    // 動画を再生し始めるときに音を消しておく。
    // 開いた直後は無音で再生され、プレーヤーの音量ボタンで音を出せる。
    // 不意に音が出ると困る場面のほうが多いので、既定では音を消している。
    //
    // ここで書くのは「はじめて開いたときの値」で、画面右上の「設定」から
    // 変更できる。変えた内容はそのブラウザに覚えさせるので、
    // 同じページを見ている他の人には影響しない。
    'video_muted' => true,

    // 動画を再生するときの表示の大きさ。こちらも「設定」から変更できる。
    //
    //   'original' … 動画そのものの大きさで表示する。
    //                画面に収まらないときだけ、収まる大きさまで縮める。
    //   'fit'      … 画面の幅いっぱいまで広げる。
    'video_size' => 'original',

    // 削除したファイル・フォルダの退避先。各ルートのフォルダからの相対パスで指定する。
    // 先頭がドットの名前にしておくと、一覧には表示されない。
    'trash_dir' => '.trash',

    // 新しい名前として受け付ける最大文字数
    'max_name_length' => 100,
];
